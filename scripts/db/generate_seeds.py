# --------------------------------------------------------------------------- helpers


def q(value) -> str:
    """SQL literal (MySQL default sql_mode: backslash is an escape character)."""
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, (int, Decimal)):
        return str(value)
    if isinstance(value, float):
        return repr(round(value, 6))
    s = str(value).replace("\\", "\\\\").replace("'", "''")
    return f"'{s}'"


def money(x) -> Decimal:
    return Decimal(x).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)


def insert_rows(table: str, cols: list[str], rows: list[list[str]], chunk: int = 200) -> str:
    """Multi-row INSERT; rows are lists of already-rendered SQL expressions."""
    out = []
    for i in range(0, len(rows), chunk):
        part = rows[i : i + chunk]
        out.append(f"INSERT INTO {table} ({', '.join(cols)}) VALUES\n")
        out.append(",\n".join("(" + ", ".join(r) + ")" for r in part) + ";\n")
    return "".join(out)


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"  wrote {path.relative_to(ROOT)}")


def day_expr(days_ago: int) -> str:
    return "CURDATE()" if days_ago == 0 else f"CURDATE() - INTERVAL {days_ago} DAY"


def ts_expr(days_ago: int, minutes_after_midnight: int) -> str:
    """A DATETIME relative to today, as SQL (negative minutes reach into the day before)."""
    return f"(TIMESTAMP({day_expr(days_ago)}) + INTERVAL {minutes_after_midnight} MINUTE)"


# --------------------------------------------------------------------------- geometry


def haversine_km(lat1, lon1, lat2, lon2) -> float:
    r = 6371.0
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dp, dl = p2 - p1, math.radians(lon2 - lon1)
    a = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * r * math.asin(math.sqrt(a))


def project_on_route(lat, lon, waypoints):
    """(offset_km, km_marker, node) of the closest point on the waypoint polyline."""
    best = None
    km_before = 0.0
    for (_, la1, lo1, node1), (_, la2, lo2, node2) in zip(waypoints, waypoints[1:]):
        seg_km = haversine_km(la1, lo1, la2, lo2)
        # Local equirectangular projection: accurate to metres over 50 km segments.
        kx = 111.32 * math.cos(math.radians((la1 + la2) / 2))
        ky = 110.57
        ax, ay = 0.0, 0.0
        bx, by = (lo2 - lo1) * kx, (la2 - la1) * ky
        px, py = (lon - lo1) * kx, (lat - la1) * ky
        seg2 = bx * bx + by * by
        t = max(0.0, min(1.0, (px * bx + py * by) / seg2)) if seg2 else 0.0
        cx, cy = ax + t * bx, ay + t * by
        offset = math.hypot(px - cx, py - cy)
        cand = (offset, km_before + t * seg_km, node1 if t < 0.5 else node2)
        if best is None or cand[0] < best[0]:
            best = cand
        km_before += seg_km
    return best


def route_length_km(waypoints) -> float:
    return sum(haversine_km(a[1], a[2], b[1], b[2]) for a, b in zip(waypoints, waypoints[1:]))


