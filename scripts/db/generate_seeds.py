"""
Generate the MySQL seed files in database/mysql/seeds/ deterministically.

    pip install -r scripts/db/requirements.txt
    python scripts/db/generate_seeds.py

Inputs
  * scripts/db/seed_data.py   cities, pricing, demo users/vehicles/stations, corridors
  * scripts/db/raw/*.json     real stations from Open Charge Map (optional; written
                              by fetch_stations.py). Without them, each city gets
                              only the backend's three demo stations.
Outputs
  * seeds/common/02_pricing.sql, 03_corridors.sql, 04_users.sql   (replicated)
  * seeds/<city>/01_stations.sql, 02_slots.sql, 03_bookings.sql   (fragmented)

Same inputs -> byte-identical outputs: a fixed random seed drives every choice,
bcrypt salts are derived from it too, and dates are written as SQL expressions
relative to CURDATE(), so the files never need regenerating as time passes.
"""

