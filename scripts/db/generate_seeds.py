def ocm_station(poi: dict):
    """One OCM POI -> station dict with bookable chargers, or None if unusable."""
    if poi.get("StatusTypeID") in OCM_EXCLUDED_STATUS:
        return None
    a = poi.get("AddressInfo") or {}
    lat, lon = a.get("Latitude"), a.get("Longitude")
    if lat is None or lon is None:
        return None
    plugs = []
    for c in poi.get("Connections") or []:
        conn = OCM_CONNECTORS.get(c.get("ConnectionTypeID"))
        if not conn or c.get("StatusTypeID") in OCM_EXCLUDED_STATUS:
            continue
        kw = float(c.get("PowerKW") or 0)
        # Missing or implausible ratings (e.g. 3 kW on CCS2, 100 kW on Type2) -> standard value.
        if CURRENT[conn] == "DC" and not 10 <= kw <= 350:
            kw = OCM_DEFAULT_KW[conn]
        if CURRENT[conn] == "AC" and not 3 <= kw <= 43:
            kw = OCM_DEFAULT_KW[conn]
        qty = max(1, min(int(c.get("Quantity") or 1), 4))
        plugs.extend([(conn, round(kw, 2))] * qty)
    plugs = plugs[:MAX_CHARGERS_PER_STATION]
    if not plugs:
        return None
    title = " ".join((a.get("Title") or "").split()) or f"Charging station (OCM #{poi['ID']})"
    parts = []
    for key in ("AddressLine1", "AddressLine2", "Town", "Postcode"):
        v = " ".join(str(a.get(key) or "").split())
        if v and v not in parts:
            parts.append(v)
    return {
        "ocm_id": poi["ID"],
        "name": title[:255],
        "address": ", ".join(parts) or title,
        "lat": round(float(lat), 6),
        "lon": round(float(lon), 6),
        "chargers": [
            (f"CHG-{i:02d}", CURRENT[conn], kw, conn) for i, (conn, kw) in enumerate(plugs, start=1)
        ],
    }


def load_raw(name: str) -> list[dict]:
    path = RAW / name
    if not path.exists():
        return []
    return json.loads(path.read_text(encoding="utf-8"))


def pick(rng: random.Random, stations: list[dict], n: int) -> list[dict]:
    """Deterministic sample: sort by OCM id, sample, keep id order."""
    stations = sorted(stations, key=lambda s: s["ocm_id"])
    if len(stations) > n:
        stations = sorted(rng.sample(stations, n), key=lambda s: s["ocm_id"])
    return stations


